package com.genzopia.Instagame.channel_view.Fragment.DetailFragment;

public class LinkItem {
    private String title;
    private String url;

    public LinkItem(String title, String url) {
        this.title = title;
        this.url = url;
    }

    public String getTitle() {
        return title;
    }

    public String getUrl() {
        return url;
    }
}

